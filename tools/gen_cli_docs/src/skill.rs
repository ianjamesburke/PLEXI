//! Compact installed skill generated from clap and the shared release catalog.
use clap::{Command, CommandFactory};
use plexi::cli_args::Cli;
use plexi::release_catalog::{GatePath, ReleaseFeature};
use std::fmt::Write;

pub fn generate() -> String {
    let manifest: toml::Value =
        toml::from_str(include_str!("../../../Cargo.toml")).expect("root Cargo.toml must parse");
    let version = manifest["package"]["version"]
        .as_str()
        .expect("package version");
    let header = format!(
        "name: plexi-cli\ndescription: \"Operate a running Plexi host: panes, apps, contexts, notifications, workspace tools, and agent coordination.\"\nskill_version: \"6.1.2\"\nplexi_version: {version:?}\nlast_verified: \"2026-10-25\"\n"
    );
    let parsed: serde_yaml::Value = serde_yaml::from_str(&header).expect("valid skill frontmatter");
    for key in ["name", "description", "plexi_version"] {
        assert!(parsed[key].as_str().is_some_and(|s| !s.is_empty()));
    }
    let mut output = format!("---\n{header}---\n\n<!-- Generated by gen_cli_docs --skill; edit intro.md for workflows. -->\n\n{}\n\n## Feature map\n\n", include_str!("../../../skills/plexi-cli/intro.md").trim());
    let command = Cli::command();
    let gates: Vec<_> = ReleaseFeature::ALL
        .iter()
        .flat_map(|feature| {
            feature
                .owned_paths()
                .iter()
                .map(move |path| (feature.key(), *path))
        })
        .collect();
    emit_children(&mut output, &command, &[], &gates);
    output
}

fn required_gates<'a>(
    path: &[&str],
    arg: Option<&str>,
    gates: &[(&'a str, GatePath)],
) -> Vec<&'a str> {
    let mut keys = Vec::new();
    for (key, gate) in gates {
        let matches = match gate {
            GatePath::Sub(owned) => path.starts_with(owned),
            GatePath::Arg(owned, id) => path == *owned && arg == Some(*id),
        };
        if matches && !keys.contains(key) {
            keys.push(*key);
        }
    }
    keys
}

fn emit_entry(output: &mut String, text: &str, gates: &[&str]) {
    if !gates.is_empty() {
        writeln!(output, "<!-- experiment: {} -->", gates.join(", ")).unwrap();
    }
    output.push_str(text);
    if !gates.is_empty() {
        output.push_str("<!-- /experiment -->\n");
    }
}

fn emit_children(
    output: &mut String,
    command: &Command,
    parent: &[&str],
    gates: &[(&str, GatePath)],
) {
    for sub in command
        .get_subcommands()
        .filter(|sub| !sub.is_hide_set() && sub.get_name() != "help")
    {
        let mut path = parent.to_vec();
        path.push(sub.get_name());
        let keys = required_gates(&path, None, gates);
        let description = sub.get_about().map(|s| s.to_string()).unwrap_or_default();
        // Keep the index compact; long_about and flag tables belong in --help.
        let description = description.lines().next().unwrap_or_default();
        let description = description.split(". ").next().unwrap_or_default();
        let description = if description.chars().count() > 140 {
            let short: String = description.chars().take(137).collect();
            format!(
                "{}...",
                short
                    .rsplit_once(' ')
                    .map_or(short.as_str(), |(words, _)| words)
            )
        } else {
            description.to_string()
        };
        let entry = format!("- `plexi {}`: {description}\n", path.join(" "));
        emit_entry(output, &entry, &keys);
        for arg in sub.get_arguments().filter(|arg| !arg.is_hide_set()) {
            let arg_keys = required_gates(&path, Some(arg.get_id().as_str()), gates);
            if arg_keys == keys {
                continue;
            }
            let spelling = arg
                .get_long()
                .map(|s| format!("--{s}"))
                .or_else(|| arg.get_short().map(|s| format!("-{s}")))
                .unwrap_or_else(|| format!("<{}>", arg.get_id()));
            let entry = format!(
                "  - `plexi {} {spelling}` (experiment option; see command help).\n",
                path.join(" ")
            );
            emit_entry(output, &entry, &arg_keys);
        }
        emit_children(output, sub, &path, gates);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn command_additions_renames_and_hidden_paths_follow_clap() {
        let mut command = Command::new("plexi")
            .subcommand(Command::new("fresh").subcommand(Command::new("renamed")))
            .subcommand(Command::new("internal").hide(true));
        command.build();
        let mut output = String::new();
        emit_children(&mut output, &command, &[], &[]);
        assert!(output.contains("`plexi fresh renamed`"));
        assert!(!output.contains("internal"));
        assert!(!output.contains(" help"));
    }

    #[test]
    fn ownership_changes_gate_descendants_and_options_with_all_owners() {
        let command = Command::new("plexi").subcommand(
            Command::new("fresh")
                .subcommand(Command::new("child").arg(clap::Arg::new("extra").long("extra"))),
        );
        let gates = [
            ("one", GatePath::Sub(&["fresh"])),
            ("two", GatePath::Sub(&["fresh", "child"])),
            ("three", GatePath::Arg(&["fresh", "child"], "extra")),
        ];
        let mut output = String::new();
        emit_children(&mut output, &command, &[], &gates);
        assert!(output.contains("<!-- experiment: one, two -->\n- `plexi fresh child`"));
        assert!(output
            .contains("<!-- experiment: one, two, three -->\n  - `plexi fresh child --extra`"));
        let mut ungated = String::new();
        emit_children(&mut ungated, &command, &[], &[]);
        assert!(!ungated.contains("experiment:"));
    }

    #[test]
    fn generated_skill_stamps_root_version_and_valid_frontmatter() {
        let output = generate();
        let yaml = output.split("---\n").nth(1).unwrap();
        let header: serde_yaml::Value = serde_yaml::from_str(yaml).unwrap();
        let manifest: toml::Value = toml::from_str(include_str!("../../../Cargo.toml")).unwrap();
        assert_eq!(
            header["plexi_version"].as_str(),
            manifest["package"]["version"].as_str()
        );
        assert!(output.contains("<!-- experiment: mcp_client -->\n  - `plexi app open --mcp`"));
    }
}
