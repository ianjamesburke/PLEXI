use clap::Command;
use std::collections::BTreeMap;

/// Parse the Rust enum itself, so adding a variant cannot silently escape coverage.
pub fn generate(command: &Command, source: &str, data: &str) -> Result<String, String> {
    let file = syn::parse_file(source).map_err(|e| format!("Action source: {e}"))?;
    let actions = file
        .items
        .iter()
        .find_map(|item| match item {
            syn::Item::Enum(item) if item.ident == "Action" => Some(&item.variants),
            _ => None,
        })
        .ok_or("Action enum not found")?;
    let mut rows: BTreeMap<String, serde_json::Value> =
        serde_json::from_str(data).map_err(|e| e.to_string())?;
    let mut output = String::from("# UI-to-CLI parity\n\nGenerated by `cargo run -p gen_cli_docs -- --parity` from the host Action enum, clap, and `parity.json`. Do not edit this table.\n\nCLI examples use illustrative ids and names. Relative UI navigation maps to explicit CLI destinations; notes describe differences. Waivers are explicit UI-only decisions, not implemented verbs.\n\n| Action | CLI or waiver | Notes |\n|---|---|---|\n");
    for variant in actions {
        let name = variant.ident.to_string();
        let row = rows
            .remove(&name)
            .ok_or_else(|| format!("Action {name} has neither CLI mapping nor ui-only waiver"))?;
        let cli = row.get("cli").and_then(|v| v.as_str());
        let waiver = row.get("ui-only").and_then(|v| v.as_str());
        let surface = match (cli, waiver) {
            (Some(example), None) => {
                let args = std::iter::once("plexi").chain(example.split_whitespace());
                command
                    .clone()
                    .try_get_matches_from(args)
                    .map_err(|e| format!("{name}: invalid CLI mapping: {e}"))?;
                format!("`plexi {example}`")
            }
            (None, Some(reason)) if !reason.trim().is_empty() => format!("ui-only: {reason}"),
            _ => {
                return Err(format!(
                    "{name}: supply exactly one CLI mapping or nonempty waiver"
                ))
            }
        };
        let note = row.get("note").and_then(|v| v.as_str()).unwrap_or("");
        output.push_str(&format!("| `{name}` | {surface} | {note} |\n"));
    }
    if !rows.is_empty() {
        return Err(format!("unknown Actions in parity data: {:?}", rows.keys()));
    }
    Ok(output)
}
