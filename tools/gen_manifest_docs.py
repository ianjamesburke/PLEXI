#!/usr/bin/env python3
"""Generate the manifest reference from its Rust owners and valid fixture."""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "website/src/content/docs/plugin-manifest.md"


def generate() -> str:
    contract = (ROOT / "src/app/manifest_contract.rs").read_text()
    prose = "\n".join(line.removeprefix("//!").removeprefix(" ")
                      for line in contract.splitlines() if line.startswith("//!"))
    permissions = (ROOT / "src/app/permissions.rs").read_text()
    enum_impl = permissions.split("impl Capability {", 1)[1]
    names = enum_impl.split("pub fn as_str(self)", 1)[1].split("pub const ALL", 1)[0]
    wire_names = dict(re.findall(r'Self::(\w+) => "([^"]+)"', names))
    all_source = enum_impl.split("pub const ALL", 1)[1].split("];", 1)[0]
    ids = [(variant, wire_names[variant]) for variant in re.findall(r'Self::(\w+)', all_source)]
    descriptions = dict(re.findall(r'Self::(\w+) => "([^"]+)"',
                                  enum_impl.split("pub fn as_str(self)", 1)[0]))
    reserved_source = permissions.split("pub const RESERVED_CAPABILITY_IDS:", 1)[1].split(";", 1)[0]
    reserved = re.findall(r'"([^"]+)"', reserved_source)
    if not ids or not reserved:
        raise ValueError("manifest capability registry could not be extracted")
    rows = [f"| `{wire}` | Available | {descriptions[variant]} |" for variant, wire in ids]
    rows += [f"| `{wire}` | Reserved | No host projection serves this ID yet. |" for wire in reserved]
    fixture = (ROOT / "tests/fixtures/schema2/good.toml").read_text().rstrip()
    return ("---\ntitle: Plugin manifest\ndescription: Schema-2 capability and contribution contract.\n---\n\n"
            "<!-- Generated by tools/gen_manifest_docs.py. Run just gen-manifest-docs. -->\n\n"
            + prose + "\n\n## Capability registry\n\n"
            "| ID | Availability | Purpose |\n|---|---|---|\n" + "\n".join(rows)
            + "\n\n## Manifest fixture\n\nThis WASM fixture declares a view and a command. Its entry file is `main.wasm`.\n\n```toml\n"
            + fixture + "\n```\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        content = generate()
        if args.check:
            if OUTPUT.read_text() != content:
                raise ValueError("manifest reference is stale; run just gen-manifest-docs")
            print("Manifest reference is up to date.")
        else:
            OUTPUT.write_text(content)
            print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    except (OSError, ValueError, KeyError, IndexError) as error:
        parser.exit(1, f"gen_manifest_docs: {error}\n")


if __name__ == "__main__":
    main()
