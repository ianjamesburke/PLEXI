import { copyFileSync, existsSync, readFileSync, unlinkSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import type { PlexiCliClient } from "./cli-client.ts";

export const PLEXI_PI_PACKAGE_ACTIVE_GLOBAL = "__PLEXI_PI_PACKAGE_ACTIVE__";
export const LEGACY_PI_EXTENSION_FILENAME = "plexi-agent-state.ts";

export function isLegacyPlexiPiExtensionContent(content: string): boolean {
  return (
    content.includes("Plexi-managed agent state extension.") ||
    (content.includes("const hookCommand =") && content.includes('PLEXI_AGENT_NAME: "pi"'))
  );
}

/**
 * Detect and migrate `~/.pi/agent/extensions/plexi-agent-state.ts` if it was
 * generated by `plexi agent hook install --pi`. Preserves unknown user-authored
 * extensions untouched.
 */
export function migrateLegacyPiHook(options: { homeDir?: string; extensionPath?: string } = {}): {
  found: boolean;
  migrated: boolean;
  preservedUnknown: boolean;
  extensionPath: string;
  backupPath: string;
  error?: string;
} {
  const baseHome = options.homeDir ?? process.env.HOME ?? homedir();
  const extensionPath =
    options.extensionPath ??
    join(baseHome, ".pi", "agent", "extensions", LEGACY_PI_EXTENSION_FILENAME);
  const backupPath = `${extensionPath}.plexi-hook.bak`;

  if (!existsSync(extensionPath)) {
    return {
      found: false,
      migrated: false,
      preservedUnknown: false,
      extensionPath,
      backupPath,
    };
  }

  try {
    const content = readFileSync(extensionPath, "utf8");
    if (!isLegacyPlexiPiExtensionContent(content)) {
      return {
        found: true,
        migrated: false,
        preservedUnknown: true,
        extensionPath,
        backupPath,
      };
    }
    if (!existsSync(backupPath)) {
      copyFileSync(extensionPath, backupPath);
    }
    unlinkSync(extensionPath);
    return {
      found: true,
      migrated: true,
      preservedUnknown: false,
      extensionPath,
      backupPath,
    };
  } catch (err) {
    return {
      found: true,
      migrated: false,
      preservedUnknown: false,
      extensionPath,
      backupPath,
      error: (err as Error).message,
    };
  }
}

export function markPiPlexiPackageActive(): void {
  (globalThis as Record<string, unknown>)[PLEXI_PI_PACKAGE_ACTIVE_GLOBAL] = true;
  process.env.PLEXI_PI_PACKAGE_ACTIVE = "1";
}

export function resolveSessionIdFromContext(ctx: any): string {
  try {
    const fromId = ctx?.sessionManager?.getSessionId?.();
    if (typeof fromId === "string" && fromId.trim()) return fromId.trim();
    const fromFile = ctx?.sessionManager?.getSessionFile?.();
    if (typeof fromFile === "string" && fromFile.trim()) return fromFile.trim();
  } catch {
    // ignore
  }
  return process.env.PLEXI_PI_SESSION_ID?.trim() || `pi-pane-${process.env.PLEXI_PANE_ID ?? "local"}`;
}

export class PlexiLifecycleReporter {
  private client: PlexiCliClient;
  private lastState?: string;
  private lastDetail?: string;

  constructor(client: PlexiCliClient) {
    this.client = client;
  }

  async report(
    state: "working" | "blocked" | "idle",
    options: {
      detail?: string;
      sessionId?: string;
      blockedReason?: "permission_prompt" | "question" | "usage_limit" | "error";
    } = {},
  ): Promise<void> {
    if (!this.client.getAttachConfig().attached) return;
    const key = `${state}:${options.detail ?? ""}:${options.blockedReason ?? ""}`;
    if (this.lastState === key && this.lastDetail === options.sessionId) {
      return;
    }
    this.lastState = key;
    this.lastDetail = options.sessionId;
    await this.client.reportAgentState({
      state,
      detail: options.detail,
      sessionId: options.sessionId,
      blockedReason: options.blockedReason,
    });
  }
}
